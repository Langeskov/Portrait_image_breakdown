"""Unified guidance engine for portrait photography.

This module is the single source of truth for "what should happen next" in a
portrait shoot.  It replaces duplicated if/else chains that were scattered
across suggestion.py and photographer_cues.py.

Design principles:
  - One PRIMARY instruction per frame (最多加一个 SECONDARY).
  - Three result states: ADJUST / HOLD / INSUFFICIENT_EVIDENCE.
  - Priority: visibility > silhouette conflict > balance > body curve > head > composition.
  - Cues must be speakable to a model — no jargon, no abstract concepts.
  - Internal direction uses semantic enum (never bare "left"/"right").
  - Cue text is generated by a render layer, not hardcoded in logic.
"""
from __future__ import annotations

import dataclasses
from enum import Enum
from typing import Optional

from core.action_classifier import ActionCategory, ActionResult
from core.camera_analyzer import CameraResult, ShotType
from core.composition import CompositionResult
from core.orientation import FacingDirection, OrientationResult


# ---------------------------------------------------------------------------
# Direction enum — semantic, unambiguous
# ---------------------------------------------------------------------------

class Direction(Enum):
    """Semantic direction for guidance actions.

    SUBJECT_* = relative to the subject's body (your left, your right).
    IMAGE_*   = relative to the image frame (left side of the photo).
    POSTURAL  = body-mechanics directions (not left/right).
    STATE     = hold / maintain current state.
    CAMERA    = photographer movement.
    """
    # Subject-relative
    SUBJECT_LEFT = "subject_left"
    SUBJECT_RIGHT = "subject_right"
    # Postural / body mechanics
    OUTWARD = "outward"
    BACKWARD = "backward"
    FORWARD = "forward"
    STAGGER = "stagger"
    SHIFT = "shift"
    CURVE = "curve"
    TILT = "tilt"
    TURN_BACK = "turn_back"
    # State
    HOLD = "hold"
    # Camera
    CAMERA_BACK = "camera_back"
    CAMERA_FORWARD = "camera_forward"


# ---------------------------------------------------------------------------
# Data types
# ---------------------------------------------------------------------------

class GuidanceState(Enum):
    ADJUST = "adjust"
    HOLD = "hold"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"


class GuidancePriority(Enum):
    VISIBILITY = 1
    SILHOUETTE = 2
    BALANCE = 3
    BODY_CURVE = 4
    HEAD_GAZE = 5
    COMPOSITION = 6


@dataclasses.dataclass(frozen=True)
class GuidanceAction:
    priority: GuidancePriority
    category: str          # "model" | "camera" | "composition"
    target: str            # e.g. "legs", "left_arm", "head", "torso"
    direction: Direction   # semantic direction, never ambiguous
    reason: str            # technical explanation (language-independent concept)
    stop_condition: Optional[str] = None
    cue: str = ""          # populated by render_cue(); empty = needs rendering


@dataclasses.dataclass(frozen=True)
class GuidanceResult:
    state: GuidanceState
    primary: Optional[GuidanceAction]
    secondary: Optional[GuidanceAction]
    all_actions: tuple[GuidanceAction, ...]
    hold_message: str = ""

    def speakable(self, lang: str = "zh") -> str:
        """The instruction to actually say on set."""
        if self.state == GuidanceState.HOLD:
            return self.hold_message
        if self.state == GuidanceState.INSUFFICIENT_EVIDENCE:
            return _HOLD_FALLBACK[lang]
        parts = []
        if self.primary:
            parts.append(self.primary.cue or render_cue(self.primary, lang))
        if self.secondary:
            parts.append(self.secondary.cue or render_cue(self.secondary, lang))
        return " ".join(parts) if parts else _DEFAULT_HOLD[lang]


